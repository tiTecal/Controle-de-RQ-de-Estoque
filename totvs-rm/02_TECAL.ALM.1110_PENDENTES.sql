/*
 * Sentença SQL TOTVS RM (wsConsultaSQL)
 * Código da Sentença: TECAL.ALM.1110_PENDENTES
 * Sistema: T (Gestão de Estoque, Compras e Faturamento / Nucleus)
 * Parâmetros: :CODCOLIGADA
 *
 * Objetivo:
 * Listar todos os movimentos 1.1.10 ("Baixa de Estoque", faturados a partir do 1.1.13)
 * não cancelados cujos campos complementares (retirado_por, data_retirada, hora_retirada)
 * ainda NÃO estão preenchidos na tabela TMOVCOMPL.
 */

SELECT
    M.CODCOLIGADA,
    M.IDMOV,
    ISNULL(M.NUMEROMOV, CAST(M.IDMOV AS VARCHAR(20))) AS NUMEROMOV,
    M.CODTMV,
    M.CODFILIAL,
    ISNULL(M.CODLOC, '') AS CODLOC,
    ISNULL(LOC.NOME, '') AS NOMELOCAL,
    CONVERT(VARCHAR(19), M.DATAEMISSAO, 126) AS DATAEMISSAO,
    ISNULL(M.CODUSUARIO, '') AS USUARIOESTOQUISTA,
    ISNULL(M.CODCCUSTO, '') AS CODCCUSTO,
    ISNULL(CC.NOME, '') AS NOMECCUSTO,
    ISNULL(ORIG.NUMEROMOV_ORIGEM, '') AS NUMEROREQUISICAO1113,
    ISNULL(ORIG.SOLICITANTE_ORIGEM, ISNULL(M.CODUSUARIO, '')) AS SOLICITANTE,
    ISNULL(ITENS_AGG.QTD_ITENS, 0) AS QTDITENS
FROM TMOV M WITH (NOLOCK)
LEFT JOIN TMOVCOMPL MC WITH (NOLOCK)
    ON MC.CODCOLIGADA = M.CODCOLIGADA
   AND MC.IDMOV = M.IDMOV
LEFT JOIN GCCUSTO CC WITH (NOLOCK)
    ON CC.CODCOLIGADA = M.CODCOLIGADA
   AND CC.CODCCUSTO = M.CODCCUSTO
LEFT JOIN TLOC LOC WITH (NOLOCK)
    ON LOC.CODCOLIGADA = M.CODCOLIGADA
   AND LOC.CODFILIAL = M.CODFILIAL
   AND LOC.CODLOC = M.CODLOC
OUTER APPLY (
    SELECT TOP 1
        ISNULL(M13.NUMEROMOV, CAST(M13.IDMOV AS VARCHAR(20))) AS NUMEROMOV_ORIGEM,
        ISNULL(M13.CODUSUARIO, '') AS SOLICITANTE_ORIGEM
    FROM TMOVRELAC REL WITH (NOLOCK)
    INNER JOIN TMOV M13 WITH (NOLOCK)
        ON M13.CODCOLIGADA = REL.CODCOLORIGEM
       AND M13.IDMOV = REL.IDMOVORIGEM
    WHERE REL.CODCOLDESTINO = M.CODCOLIGADA
      AND REL.IDMOVDESTINO = M.IDMOV
      AND M13.CODTMV = '1.1.13'
    ORDER BY M13.IDMOV DESC
) ORIG
OUTER APPLY (
    SELECT COUNT(1) AS QTD_ITENS
    FROM TITMMOV I WITH (NOLOCK)
    WHERE I.CODCOLIGADA = M.CODCOLIGADA
      AND I.IDMOV = M.IDMOV
) ITENS_AGG
WHERE M.CODCOLIGADA = :CODCOLIGADA
  AND M.CODTMV = '1.1.10'
  AND ISNULL(M.STATUS, '') <> 'C'
  AND (
        MC.IDMOV IS NULL
        OR MC.RETIRADO_POR IS NULL
        OR LTRIM(RTRIM(CAST(MC.RETIRADO_POR AS VARCHAR(60)))) = ''
        OR MC.DATA_RETIRADA IS NULL
        OR LTRIM(RTRIM( CONVERT(VARCHAR(20), MC.DATA_RETIRADA, 126) )) = ''
        OR MC.HORA_RETIRADA IS NULL
        OR LTRIM(RTRIM(CAST(MC.HORA_RETIRADA AS VARCHAR(20)))) = ''
      )
ORDER BY M.IDMOV DESC;
